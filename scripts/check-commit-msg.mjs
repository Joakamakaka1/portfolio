// Enforces Conventional Commits (https://www.conventionalcommits.org) on the subject line.
import { readFileSync } from "node:fs";

const TYPES = [
  "feat",
  "fix",
  "docs",
  "style",
  "refactor",
  "perf",
  "test",
  "build",
  "ci",
  "chore",
  "revert",
];
const MAX_SUBJECT_LENGTH = 72;

const file = process.argv[2];
if (!file) {
  console.error("usage: check-commit-msg.mjs <commit message file>");
  process.exit(2);
}

const subject = readFileSync(file, "utf8").split("\n")[0].trim();
const pattern = new RegExp(`^(${TYPES.join("|")})(\\([a-z0-9-]+\\))?!?: \\S.*$`);

// Merge and revert commits are generated by git, not written by hand.
const isGenerated = /^(Merge|Revert) /.test(subject);

if (!isGenerated && !pattern.test(subject)) {
  console.error(`Commit subject is not a Conventional Commit:\n  ${subject}`);
  console.error(`Expected "<type>(<optional scope>): <summary>" with type in: ${TYPES.join(", ")}`);
  process.exit(1);
}

if (subject.length > MAX_SUBJECT_LENGTH) {
  console.error(
    `Commit subject has ${subject.length} characters; the limit is ${MAX_SUBJECT_LENGTH}.`,
  );
  process.exit(1);
}
